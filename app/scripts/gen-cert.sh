#!/usr/bin/env bash
# ---------------------------------------------------------------------
# สร้างใบรับรองแบบลงนามด้วยตนเอง (self-signed) สำหรับสภาพแวดล้อมพัฒนา
# และทดสอบ เพื่อให้ระบบให้บริการผ่าน HTTPS ได้ตามที่ NFR-01 กำหนด
#
# ใบรับรองครอบคลุมทั้ง localhost และหมายเลขไอพีของเครื่องในวงแลนปัจจุบัน
# เพื่อให้เปิดใช้งานจากเครื่องอื่นหรือจากมือถือในวงเดียวกันได้ ซึ่งจำเป็น
# ต่อการสาธิตการแสดงผลบนอุปกรณ์เคลื่อนที่ตาม NFR-03
#
# ถ้าย้ายไปใช้เครือข่ายอื่นแล้วหมายเลขไอพีเปลี่ยน ให้ลบโฟลเดอร์ certs/
# แล้วรันสคริปต์นี้ใหม่
#
# เมื่อนำระบบไปติดตั้งใช้งานจริงที่ร้าน ให้เปลี่ยนไปใช้ใบรับรองที่ออกโดย
# ผู้ให้บริการที่เชื่อถือได้
# ---------------------------------------------------------------------
set -euo pipefail

CERT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/certs"
mkdir -p "$CERT_DIR"

if [[ -f "$CERT_DIR/cert.pem" && -f "$CERT_DIR/key.pem" ]]; then
  echo "มีใบรับรองอยู่แล้วที่ $CERT_DIR — ข้ามขั้นตอนนี้"
  echo "ถ้าต้องการสร้างใหม่ ให้ลบไฟล์ในโฟลเดอร์นั้นก่อน"
  exit 0
fi

# รวบรวมหมายเลขไอพีของทุกการ์ดเครือข่ายที่ใช้งานอยู่
SAN="DNS:localhost,IP:127.0.0.1"
for iface in $(ifconfig -l 2>/dev/null || true); do
  ip="$(ipconfig getifaddr "$iface" 2>/dev/null || true)"
  if [[ -n "$ip" ]]; then
    SAN="$SAN,IP:$ip"
    echo "พบเครื่องอยู่ที่ $ip บนการ์ด $iface"
  fi
done

openssl req -x509 -newkey rsa:2048 -nodes -days 825 \
  -keyout "$CERT_DIR/key.pem" \
  -out "$CERT_DIR/cert.pem" \
  -subj "/C=TH/O=SOML/CN=localhost" \
  -addext "subjectAltName=$SAN"

chmod 600 "$CERT_DIR/key.pem"
echo "สร้างใบรับรองสำเร็จที่ $CERT_DIR"
echo "ครอบคลุม: $SAN"
echo "เบราว์เซอร์จะเตือนว่าใบรับรองไม่น่าเชื่อถือในครั้งแรก ให้กดยอมรับเพื่อใช้งานต่อ"
