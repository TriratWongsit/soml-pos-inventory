def box(head, items, color, dots=True):
    li = ''.join('<div class="li"><span class="dot" style="background:%s"></span><span>%s</span></div>' % (color, x)
                 if dots else '<div class="li"><span class="tri">▸</span><span>%s</span></div>' % x for x in items)
    return ('<div class="box" style="--c:%s"><div class="bh" style="color:%s;border-bottom-color:%s">%s</div>'
            '<div class="bb">%s</div></div>') % (color, color, color, head, li)


def table(head, rows, widths=None, small=False):
    w = ''.join('<col style="width:%s">' % x for x in widths) if widths else ''
    th = ''.join('<th>%s</th>' % h for h in head)
    tr = ''.join('<tr>%s</tr>' % ''.join('<td>%s</td>' % c for c in r) for r in rows)
    return '<table class="t%s"><colgroup>%s</colgroup><thead><tr>%s</tr></thead><tbody>%s</tbody></table>' % (
        ' sm' if small else '', w, th, tr)


def img(src, h, cap=None, w=None):
    st = 'max-height:%dpx' % h + (';max-width:%dpx' % w if w else '')
    c = '<div class="cap">%s</div>' % cap if cap else ''
    return '<div class="fig"><img src="%s" style="%s">%s</div>' % (A + src, st, c)


def note(t):
    return '<div class="note">%s</div>' % t


def ref(t):
    return '<div class="ref">อยู่ในเล่ม: %s</div>' % t


