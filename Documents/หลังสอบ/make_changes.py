def k_where(anchors):
    if not anchors:
        return '-'
    start = page_of('ตารางที่ซ.1ข้อเสนอแนะ', FRONT) if any(a.startswith(('ตารางที่ซ', 'รูปที่ซ')) for a in anchors) else FRONT
    return ', '.join(label(a, start if a.startswith(('ตารางที่ซ', 'รูปที่ซ')) else FRONT) for a in anchors)


def k_table(who):
    rows = [k for k in KS if who in k[1]]
    out = ['<table><tr><th style="width:7%">รหัส</th><th style="width:30%">ข้อเสนอแนะในวันสอบ</th><th>สิ่งที่แก้</th><th style="width:16%">เล่มใหม่</th></tr>']
    for code, _, said, fix, anchors in rows:
        out.append('<tr><td>%s</td><td>%s</td><td>%s</td><td><b>%s</b></td></tr>' % (code, said, fix, k_where(anchors)))
    return ''.join(out) + '</table>'


