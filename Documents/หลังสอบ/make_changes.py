import io, os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
BOOK = os.path.join(HERE, '..', 'เอกสารรูปเล่ม', 'รวมเล่ม', 'ปริญญานิพนธ์_อำพรOMS_รวมเล่ม.pdf')

n = int(re.search(r'Pages:\s+(\d+)', subprocess.run(['pdfinfo', BOOK], capture_output=True, text=True).stdout).group(1))
PAGES = [re.sub(r'[\s\u2060\u200d]+', '', subprocess.run(['pdftotext', '-f', str(i), '-l', str(i), '-layout', BOOK, '-'],
                                         capture_output=True, text=True).stdout) for i in range(1, n + 1)]
# ส่วนนำจบที่หน้าก่อน "บทที่ 1 บทนำ"
FRONT = next(i for i, t in enumerate(PAGES) if t.startswith('บทที่1บทนำ'))


def page_of(anchor, after=0):
    key = re.sub(r'\s+', '', anchor)
    for i in range(after, n):
        if key in PAGES[i]:
            return i
    raise SystemExit('ไม่พบข้อความในเล่ม: ' + anchor)


def label(anchor, after=0):
    i = page_of(anchor, after)
    return 'หน้า %d' % (i - FRONT + 1) if i >= FRONT else None


