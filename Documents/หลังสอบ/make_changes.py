def where(anchor):
    if anchor is None:
        return 'ทั้งเล่ม'
    if anchor in FRONT_NAMES:
        return FRONT_NAMES[anchor]
    after = FRONT if not anchor.startswith('เอกสารอ้างอิง') else 0
    if anchor == 'เอกสารอ้างอิง[1]':
        i = next(i for i, t in enumerate(PAGES) if t.startswith('เอกสารอ้างอิง[1]'))
        return 'หน้า %d' % (i - FRONT + 1)
    if anchor == 'ลอยเวิร์ส':
        return label('มีระบบที่เชื่อมโยงการขายหน้าร้านกับคลังสินค้าแบบทันที', FRONT) or ''
    return label(anchor, after) or 'ส่วนนำ'


def table(rows):
    out = ['<table><tr><th style="width:15%">เล่มที่พิมพ์ส่ง</th><th style="width:22%">อาจารย์ทำเครื่องหมาย</th>'
           '<th>แก้อย่างไร</th><th style="width:13%">เล่มใหม่</th></tr>']
    for old, mark, fix, anchor in rows:
        out.append('<tr><td>%s</td><td>%s</td><td>%s</td><td><b>%s</b></td></tr>' % (old, mark, fix, where(anchor)))
    return ''.join(out) + '</table>'


