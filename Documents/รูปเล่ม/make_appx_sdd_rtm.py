def routes():
    js = io.open(os.path.join(SOML, 'backend', 'app.js'), encoding='utf-8').read()
    out = ['| วิธี | เส้นทาง | สิทธิ์ | ฟังก์ชัน | โมดูล | กรณีการใช้งาน |', '|---|---|---|---|:---:|:---:|']
    n = 0
    for m in re.finditer(r"app\.(get|post|put|patch)\('([^']+)',\s*(.*?)\);\s*(?://\s*(.*))?$", js, re.M):
        meth, path, args, note = m.groups()
        if path == '/api/health':
            continue
        roles = re.search(r"requireRole\(([^)]*)\)", args)
        if roles:
            who = ', '.join(ROLE[r.strip(" '")] for r in roles.group(1).split(','))
        elif 'verifyToken' in args:
            who = 'ทุกบทบาทที่เข้าสู่ระบบแล้ว'
        elif path == '/api/events':
            who = 'ทุกบทบาท ตรวจโทเคนในสตริงคำค้น'
        else:
            who = 'ไม่ต้องเข้าสู่ระบบก่อน'
        fn = args.split(',')[-1].strip()
        mod = MOD_OF.get(fn.split('.')[0], '-')
        uc = ', '.join(re.findall(r'UC-\d\d', note or '')) or ('UC-02' if mod == 'BE-02' else '-')
        out.append('| %s | `%s` | %s | `%s` | %s | %s |' % (meth.upper(), path, who, fn, mod, uc))
        n += 1
    return '\n'.join(out), n

