def data_dictionary():
    sql = io.open(os.path.join(SOML, 'db', 'schema', 'schema.sql'), encoding='utf-8').read()
    out, k = [], 0
    for m in re.finditer(r'CREATE TABLE (\w+) \((.*?)\n\) ENGINE', sql, re.S):
        name, body = m.group(1), m.group(2)
        pk = re.search(r'PRIMARY KEY \((\w+)\)', body).group(1)
        uniq = set(re.findall(r'UNIQUE KEY \w+ \((\w+)\)', body))
        fk = dict(re.findall(r'FOREIGN KEY \((\w+)\)\s+REFERENCES (\w+)\(', body))
        rows = []
        for line in body.split('\n'):
            c = re.match(r'\s+(\w+)\s+(.+?)\s+(NOT NULL|NULL)\b(.*?)COMMENT \'([^\']*)\'', line)
            if not c:
                continue
            col, typ, null, rest, comment = c.groups()
            typ = re.sub(r'\s+', ' ', typ.replace("\n", ' ')).strip()
            if typ.startswith('ENUM'):
                typ = 'ENUM'
            key = 'คีย์หลัก' if col == pk else ('คีย์นอกไปยัง `%s`' % fk[col] if col in fk else ('ห้ามซ้ำ' if col in uniq else ''))
            rows.append('| `%s` | `%s` | %s | %s | %s |' % (col, typ, 'ว่างได้' if null == 'NULL' else 'ไม่ว่าง', key or '-', clean_comment(comment)))
        k += 1
        out.append('### ข.3.%d ตาราง `%s`' % (k, name))
        out.append('')
        out.append('**ตารางที่ ข.%d** พจนานุกรมข้อมูลของตาราง `%s`' % (k + 1, name))
        out.append('')
        out.append('| คอลัมน์ | ชนิดข้อมูล | ค่าว่าง | คีย์ | คำอธิบาย |')
        out.append('|---|---|:---:|---|---|')
        out += rows
        checks = re.findall(r'CHECK \(([^)]*)\)', body)
        if checks:
            out.append('')
            out.append('ข้อบังคับของตาราง: ' + ' และ '.join('`%s`' % c for c in checks))
        out.append('')
    return '\n'.join(out)

