def exports(path):
    f = os.path.join(SOML, path)
    if os.path.isdir(f):
        f = os.path.join(f, 'index.js')
    m = re.search(r'module\.exports = \{([^}]*)\}', io.open(f, encoding='utf-8').read())
    names = [x.strip() for x in m.group(1).split(',') if x.strip()]
    return ', '.join('`%s`' % n for n in names)

